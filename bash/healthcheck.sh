#!/bin/bash

# ================================
# Health Check скрипт
# Проверяет основные параметры сервера
# Выход с кодом 0 = всё хорошо, 1 = есть проблемы
# ================================

# Счётчик ошибок — увеличивается при каждой неудавшейся проверке
ERRORS=0

# Вспомогательная функция: проверяет код возврата предыдущей команды
# $? == 0 → команда прошла успешно → печатаем ✅
# $? != 0 → команда упала → печатаем ❌ и увеличиваем счётчик ошибок
check() {
    if [ $? -eq 0 ]; then
        echo "✅ $1"
    else
        echo "❌ $1"
        ERRORS=$((ERRORS + 1))  # Арифметика в bash: $((выражение))
    fi
}

echo "=== Health Check $(date) ==="
echo ""

# ─── Проверка диска ───
# df / — информация о файловой системе корневого раздела
# awk 'NR==2' — берём вторую строку (первая — заголовок)
# '{print $5}' — берём пятый столбец (Use%)
# tr -d '%' — удаляем символ % чтобы сравнивать как число
DISK=$(df / | awk 'NR==2 {print $5}' | tr -d '%')
# Проверяем: занято меньше 80%? Если да — команда вернёт 0 (успех)
[ "$DISK" -lt 80 ]
check "Диск: ${DISK}% занято"

# ─── Проверка памяти ───
# free — информация о RAM
# awk 'NR==2 {print $4}' — вторая строка (Mem:), четвёртый столбец (available)
FREE_MEM=$(free | awk 'NR==2 {print $4}')
# Проверяем: свободно больше 100MB (100000 KB)?
[ "$FREE_MEM" -gt 100000 ]
# free -h — в человекочитаемом формате для вывода пользователю
check "Память: свободно $(free -h | awk 'NR==2 {print $4}')"

# ─── Проверка Docker ───
# systemctl is-active — возвращает 0 если сервис active
systemctl is-active docker > /dev/null 2>&1  # > /dev/null 2>&1 — подавляем вывод
check "Docker запущен"

# ─── Проверка интернета ───
# ping -c 1 — отправляем один пакет
# 8.8.8.8 — Google DNS, почти всегда доступен
ping -c 1 8.8.8.8 > /dev/null 2>&1
check "Интернет доступен"

echo ""

# Итог: если счётчик ошибок = 0 → всё хорошо
if [ "$ERRORS" -eq 0 ]; then
    echo "🟢 Сервер в норме"
else
    echo "🔴 Найдено проблем: $ERRORS"
fi
