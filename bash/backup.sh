#!/bin/bash

# ================================
# Скрипт автоматического бэкапа
# Создаёт архив папки проекта с датой в имени файла
# Старые бэкапы (>7 дней) удаляются автоматически
# ================================

# Что бэкапим
SOURCE_DIR="/home/ubuntu/devops-lab"
# Куда сохраняем бэкапы
BACKUP_DIR="/home/ubuntu/backups"
# Текущая дата и время — добавляем в имя файла чтобы каждый бэкап был уникальным
DATE=$(date +%Y-%m-%d_%H-%M-%S)
# Итоговое имя файла, например: backup_2026-03-30_14-30-00.tar.gz
BACKUP_NAME="backup_$DATE.tar.gz"

# Функция логирования с временной меткой
log() {
    echo "[$(date +%H:%M:%S)] $1"
}

# Создаём папку для бэкапов если она не существует
# -d проверяет что путь является директорией
if [ ! -d "$BACKUP_DIR" ]; then
    mkdir -p "$BACKUP_DIR"  # -p создаёт все промежуточные папки
    log "Создана папка для бэкапов: $BACKUP_DIR"
fi

log "Начинаю бэкап папки: $SOURCE_DIR"

# Создаём архив
# tar флаги:
#   -c = create (создать архив)
#   -z = gzip (сжать)
#   -f = file (имя файла архива)
# 2>/dev/null — подавляем предупреждения (например о меняющихся файлах)
tar -czf "$BACKUP_DIR/$BACKUP_NAME" "$SOURCE_DIR" 2>/dev/null

# $? — код возврата последней команды (0 = успех, любое другое = ошибка)
if [ $? -eq 0 ]; then
    # du -sh — размер файла в человекочитаемом формате (K, M, G)
    # cut -f1 — берём только первое поле (размер без пути)
    SIZE=$(du -sh "$BACKUP_DIR/$BACKUP_NAME" | cut -f1)
    log "✅ Бэкап успешно создан: $BACKUP_NAME (размер: $SIZE)"
else
    log "❌ Ошибка при создании бэкапа!"
    exit 1
fi

# Удаляем бэкапы старше 7 дней
log "Удаляю старые бэкапы (старше 7 дней)..."
# find — ищем файлы
# -name "backup_*.tar.gz" — только файлы бэкапов
# -mtime +7 — изменённые более 7 дней назад
# -delete — удаляем найденные файлы
find "$BACKUP_DIR" -name "backup_*.tar.gz" -mtime +7 -delete

# Показываем список всех бэкапов
log "Текущие бэкапы:"
ls -lh "$BACKUP_DIR"
